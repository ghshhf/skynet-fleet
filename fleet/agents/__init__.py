"""角色编队：多智能体的能力边界与容量闸。

这个包回答两个问题：

1. **一个角色能用什么、不能用什么**（`profile.py` 的工具边界 + 深度策略）；
2. **同时能派几个活**（`capacity.py` 的容量闸）。

外加一件正事：**答卷长什么样**（`contract.py` 的五段式输出契约）。

三条都抄 DeepSeek Harness 的机制，但**不抄它的框架**——它是 Node/TS + Cordis 元框架，
本仓是 Python + 「能力清单 + 注册表」两层。一层的插件容器对现在 70 项能力的规模
是过度工程。我们要的是**机制**，不是产品。

| 模块 | 管什么 | 一句话 |
|---|---|---|
| `contract.py` | 子智能体交什么答卷 | 五段固定格式，父级只机械消费 EVIDENCE 段 |
| `profile.py` | 一个角色的边界 | provider / tool_filter / max_depth |
| `capacity.py` | 深度与容量的两个闸 | 深度锁 1、共享池、预留-释放、满则 fail-fast |
| `roster.py` | 运行时角色名册 | 把 `cards/` 读成带边界的角色并校验 |

---

## 深度与容量是**两个独立的闸**，不能混用

| 概念 | 管什么 | 本仓实现 |
|---|---|---|
| **深度**（depth） | 角色树能长多高 | `profile.max_depth`，默认 **1**（只允许直接子级） |
| **容量**（capacity） | 同一时刻能铺多宽 | `capacity.CapacityGate`，默认 **4** |

为什么深度和容量要分开：
- 深度管的是**结构**（会不会无限套娃）——一个角色能不能再往下派活；
- 容量管的是**资源**（同时有多少在跑）——跟结构无关。
把两者混成一个数，就会出现「为了限并发把递归也锁死」或「放开递归结果并发也涨」这种错。

---

## 容量闸的四条语义（逐条抄自 Harness 官方 README.zh.md）

1. **根不占名额**。顶层编排器不算在容量里。
2. **本地与外部后代共享同一个池**。不许「内部一套、外部一套」。
3. **创建前预留，完整释放后才归还**。
   ⇒ **等待中的 / 有待处理输入的 / 正在停止的，仍然占名额**。
   （这一条最容易做错：很多实现「收到回复就还名额」，于是「还在收尾的活」不占额度，
   实际并发会超过设定值。）
4. **容量耗尽时 fail-fast，立刻拒绝，绝不排队**。
   Harness 的原话理由：**排队会让「等待后代的父代理」去等「自己占着的名额」，
   互相死等。** 所以满了就返回「容量已满 + 缺几个」，让调用方自己决定等还是少派。

---

## 默认容量为什么是 4 而不是 Harness 的 8

Harness 默认 `maxActiveSubagents = 8`，但那是给 **1M 上下文 + V4** 的桌面机用的。
本机的现实（2026-10-21 实测）：
- 16GB 内存；
- 子智能体全部打**同一个**免费端点（`127.0.0.1:8787`）⇒ 并发上去互相抢额度；
- 同一个会话里 9 个子智能体的对话记录累计约 **19MB** 上下文。

⇒ **照抄 8 会翻车**。默认 4，且允许按角色/按端点再收窄。

---

## 五段式契约：父级只认 EVIDENCE

子智能体的自由文本输出是**散文**——父级想用它的证据只能整段读一遍再自己挑，
于是挑错挑不到、出了问题定位不到、它还能自由省略自己没做的事。

`contract.py` 把答卷钉成五段（顺序固定）：

    SUMMARY: 一段话，你做了什么、发生了什么
    CHANGES: 改了哪些文件，各一行说明；只读就写 "None."
    EVIDENCE: path:line-range 引用 + 关键发现，每条一个要点
    RISKS: 可能出什么问题 / 父级该复查什么
    BLOCKERS: 什么挡住了；干净收尾就写 "None."

**父级只机械消费 EVIDENCE 段**作为下一轮的工作集。

最容易写反的一处：「空段」和「合法的 `None.`」是两回事。
`None.` 是**明确的**「没有」，是合法答卷；空字符串是**什么都没说**，必须判失败。
把两者混为一谈 ⇒ 父级把「没说」当成「没有」⇒ **静默丢证据**。
`is_blank()` 与 `is_none_marker()` 就是为分开这两件事而存在的。
"""
